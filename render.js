#!/usr/bin/env node
'use strict';
/*
  render.js — timestamps.txt + audio.mp3  →  hadith-video.mp4

    node render.js                  full video
    node render.js --test 10        only the first 10 seconds
    node render.js --still 3,12.5   PNG stills at those seconds (written to the current folder)
    node render.js --workers 2      number of parallel browsers (default: min(4, CPU count))
    node render.js --lines          only regenerate lines.js from timestamps.txt

  timestamps.txt may be an SRT-style file (00:00:05,000 --> 00:00:15,000 + text)
  or one line per segment:  start | end | text | emotion_tag   (seconds).
*/
const fs = require('fs');
const os = require('os');
const path = require('path');
const cp = require('child_process');

const ROOT = __dirname;
const CFG = {
  width: 1080,
  height: 1920,
  fps: 30,
  output: 'hadith-video.mp4',
  audio: 'audio.mp3',
  timestamps: 'timestamps.txt',
  jpegQuality: 93,
};

// The SRT file has no emotion tags, so these defaults are used (same order as the lines).
const DEFAULT_TAGS = [
  'respectful', 'informative', 'solemn', 'serious', 'calm', 'calm',
  'solemn', 'serious', 'informative', 'thoughtful', 'compassionate', 'thoughtful',
  'warm', 'solemn', 'encouraging', 'thoughtful', 'warm', 'friendly',
];
const KNOWN_TAGS = new Set([
  'respectful', 'informative', 'solemn', 'serious', 'calm', 'thoughtful', 'warm',
  'compassionate', 'optimistic', 'friendly', 'encouraging', 'store',
]);

/* ---------- command line ---------- */
const argv = process.argv.slice(2);
function flag(name) { return argv.includes(name); }
function value(name) {
  const i = argv.indexOf(name);
  return i >= 0 && i + 1 < argv.length ? argv[i + 1] : null;
}

/* ---------- timestamps → lines.js ---------- */
function toSeconds(str) {
  const parts = String(str).trim().replace(',', '.').split(':').map(Number);
  if (!parts.length || parts.some((n) => Number.isNaN(n))) return NaN;
  return parts.reduce((acc, n) => acc * 60 + n, 0);
}

function parseTimestamps(raw) {
  const lines = raw.replace(/^﻿/, '').split(/\r?\n/);
  const out = [];
  const isSrt = lines.some((l) => l.includes('-->'));
  if (isSrt) {
    let cur = null;
    for (const line of lines) {
      const m = line.match(/^\s*([\d:.,]+)\s*-->\s*([\d:.,]+)/);
      if (m) {
        if (cur) out.push(cur);
        cur = { s: toSeconds(m[1]), e: toSeconds(m[2]), text: [] };
      } else if (cur) {
        if (line.trim() === '') { out.push(cur); cur = null; }
        else cur.text.push(line.trim());
      }
    }
    if (cur) out.push(cur);
    out.forEach((o) => { o.text = o.text.join(' ').trim(); o.tag = ''; });
  } else {
    for (const line of lines) {
      if (!line.trim()) continue;
      const p = line.split('|');
      if (p.length < 3) continue;
      const s = toSeconds(p[0]);
      const e = toSeconds(p[1]);
      let tag = '';
      let text;
      if (p.length >= 4) { tag = p[p.length - 1].trim().toLowerCase(); text = p.slice(2, -1).join('|').trim(); }
      else text = p.slice(2).join('|').trim();
      out.push({ s, e, text, tag });
    }
  }
  const lines2 = out.filter((o) => o.text);
  if (!lines2.length) throw new Error('No timestamp lines found in ' + CFG.timestamps);
  lines2.forEach((o, i) => {
    if (Number.isNaN(o.s) || Number.isNaN(o.e) || o.e <= o.s) {
      throw new Error('Bad time range in line ' + (i + 1) + ': ' + o.text.slice(0, 40));
    }
    if (i > 0 && o.s < lines2[i - 1].s) throw new Error('Line ' + (i + 1) + ' starts before the previous line.');
    if (!KNOWN_TAGS.has(o.tag)) o.tag = DEFAULT_TAGS[i] || 'calm';
  });
  return lines2;
}

function writeLines() {
  const tsPath = path.join(ROOT, CFG.timestamps);
  if (!fs.existsSync(tsPath)) throw new Error('Missing ' + CFG.timestamps);
  const lines = parseTimestamps(fs.readFileSync(tsPath, 'utf8'));
  const last = Math.max(...lines.map((l) => l.e));
  const duration = Math.ceil(last - 1e-9);
  const body = lines
    .map((l) => '  ' + JSON.stringify({ s: l.s, e: l.e, text: l.text, tag: l.tag }))
    .join(',\n');
  const js =
    '// Generated by render.js from ' + CFG.timestamps + ' — do not edit by hand.\n' +
    'const LINES = [\n' + body + '\n];\n' +
    'const VIDEO = ' + JSON.stringify({ width: CFG.width, height: CFG.height, fps: CFG.fps, duration }) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'lines.js'), js, 'utf8');
  return { lines, duration };
}

/* ---------- helpers ---------- */
function need(file, fatal) {
  const ok = fs.existsSync(path.join(ROOT, file));
  if (!ok) {
    const msg = 'Missing file: ' + file;
    if (fatal) throw new Error(msg);
    console.warn('WARNING: ' + msg);
  }
}

function fontReport() {
  for (const fam of ['Noto Serif Bengali', 'Amiri']) {
    const r = cp.spawnSync('fc-match', ['-f', '%{family}', fam], { encoding: 'utf8' });
    if (r.status === 0) console.log('font ' + fam + ' -> ' + r.stdout.trim());
  }
}

async function openPage(browser) {
  const ctx = await browser.newContext({
    viewport: { width: CFG.width, height: CFG.height },
    deviceScaleFactor: 1,
  });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => console.error('[page error] ' + e.message));
  page.on('console', (m) => {
    if (m.type() === 'error' || m.type() === 'warning') console.error('[page ' + m.type() + '] ' + m.text());
  });
  await page.goto('file://' + path.join(ROOT, 'index.html'));
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 120000 });
  return { ctx, page };
}

async function launch(chromium) {
  const opts = { args: ['--no-sandbox', '--font-render-hinting=none', '--disable-lcd-text'] };
  if (process.env.CHROMIUM_PATH) opts.executablePath = process.env.CHROMIUM_PATH;
  return chromium.launch(opts);
}

/* ---------- main ---------- */
async function main() {
  if (flag('--help') || flag('-h')) {
    console.log(fs.readFileSync(__filename, 'utf8').split('*/')[0].replace(/^#!.*\n/, ''));
    return;
  }
  const { lines, duration: totalDuration } = writeLines();
  console.log('lines.js written: ' + lines.length + ' lines, video length ' + totalDuration + ' s');
  if (flag('--lines')) return;

  need('index.html', true);
  need('style.css', true);
  need('art.js', true);
  need('scenes.js', true);
  need(CFG.audio, true);
  need('app-icon.jpg', false);
  need('google-play-badge.jpg', false);
  fontReport();

  const { chromium } = require('playwright');
  const fps = CFG.fps;

  /* stills */
  if (value('--still')) {
    const times = value('--still').split(',').map(Number).filter((n) => !Number.isNaN(n));
    const browser = await launch(chromium);
    const { page } = await openPage(browser);
    for (const t of times) {
      await page.evaluate((x) => window.renderAt(x), t);
      const file = path.resolve(process.cwd(), 'still_' + String(t).replace('.', '_') + '.png');
      await page.screenshot({ path: file, type: 'png' });
      console.log('still ' + t + ' s -> ' + file);
    }
    await browser.close();
    return;
  }

  /* video */
  let seconds = totalDuration;
  if (value('--test')) {
    const n = Number(value('--test'));
    if (!(n > 0)) throw new Error('--test needs a number of seconds');
    seconds = Math.min(n, totalDuration);
  }
  const totalFrames = Math.round(seconds * fps);
  const workers = Math.max(1, Math.min(Number(value('--workers')) || Math.min(4, os.cpus().length), totalFrames));
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hadith-frames-'));
  console.log('rendering ' + totalFrames + ' frames with ' + workers + ' worker(s) into ' + dir);

  let done = 0;
  let lastPct = -1;
  const per = Math.ceil(totalFrames / workers);
  const jobs = [];
  for (let w = 0; w < workers; w++) {
    const from = w * per;
    const to = Math.min(totalFrames, from + per);
    if (from >= to) continue;
    jobs.push((async () => {
      const browser = await launch(chromium);
      try {
        const { page } = await openPage(browser);
        for (let f = from; f < to; f++) {
          await page.evaluate((t) => window.renderAt(t), f / fps);
          const name = 'f' + String(f).padStart(5, '0') + '.jpg';
          await page.screenshot({ path: path.join(dir, name), type: 'jpeg', quality: CFG.jpegQuality });
          done++;
          const pct = Math.floor((done * 100) / totalFrames / 5) * 5;
          if (pct !== lastPct) { lastPct = pct; console.log('progress ' + pct + '% (' + done + '/' + totalFrames + ')'); }
        }
      } finally {
        await browser.close();
      }
    })());
  }
  await Promise.all(jobs);

  const out = path.resolve(process.cwd(), CFG.output);
  const args = [
    '-y', '-hide_banner', '-loglevel', 'error',
    '-framerate', String(fps), '-i', path.join(dir, 'f%05d.jpg'),
    '-i', path.join(ROOT, CFG.audio),
    '-filter_complex', '[1:a]apad,atrim=0:' + seconds + ',asetpts=PTS-STARTPTS[a]',
    '-map', '0:v', '-map', '[a]',
    '-c:v', 'libx264', '-preset', 'medium', '-crf', '18', '-pix_fmt', 'yuv420p', '-r', String(fps),
    '-c:a', 'aac', '-b:a', '192k',
    '-movflags', '+faststart', '-shortest', out,
  ];
  console.log('encoding with ffmpeg ...');
  const r = cp.spawnSync('ffmpeg', args, { stdio: 'inherit' });
  if (r.status !== 0) {
    console.error('ffmpeg failed (exit ' + r.status + ')');
    process.exit(1);
  }
  fs.rmSync(dir, { recursive: true, force: true });
  console.log('done -> ' + out);
}

main().catch((err) => {
  console.error(err && err.stack ? err.stack : err);
  process.exit(1);
});
